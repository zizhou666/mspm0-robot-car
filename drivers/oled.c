void OLED_DrawPixel(int16_t x, int16_t y, uint8_t color)
{
    uint16_t index;
    uint8_t mask;

    if ((x < 0) || (x >= (int16_t)OLED_WIDTH) ||
        (y < 0) || (y >= (int16_t)OLED_HEIGHT))
    {
        return;
    }

    index = (uint16_t)x + ((uint16_t)(y >> 3) * OLED_WIDTH);
    mask = (uint8_t)(1U << ((uint8_t)y & 7U));

    if (color == OLED_COLOR_WHITE)
    {
        oled_buffer[index] |= mask;
    }
    else if (color == OLED_COLOR_BLACK)
    {
        oled_buffer[index] &= (uint8_t)~mask;
    }
    else
    {
        oled_buffer[index] ^= mask;
    }
}

void OLED_DrawLine(int16_t x0, int16_t y0, int16_t x1, int16_t y1, uint8_t color)
{
    int16_t dx = oled_abs_i16((int16_t)(x1 - x0));
    int16_t sx = (x0 < x1) ? 1 : -1;
    int16_t dy = (int16_t)-oled_abs_i16((int16_t)(y1 - y0));
    int16_t sy = (y0 < y1) ? 1 : -1;
    int16_t error = (int16_t)(dx + dy);

    for (;;)
    {
        OLED_DrawPixel(x0, y0, color);
        if ((x0 == x1) && (y0 == y1))
        {
            break;
        }

        {
            int16_t error2 = (int16_t)(2 * error);
            if (error2 >= dy)
            {
                error = (int16_t)(error + dy);
                x0 = (int16_t)(x0 + sx);
            }
            if (error2 <= dx)
            {
                error = (int16_t)(error + dx);
                y0 = (int16_t)(y0 + sy);
            }
        }
    }
}

