void OLED_SetPosition(uint8_t x, uint8_t page)
{
    uint8_t commands[3];
    uint16_t column;

    if ((x >= OLED_WIDTH) || (page >= OLED_PAGE_COUNT))
    {
        return;
    }

    column = (uint16_t)x + (uint16_t)OLED_COLUMN_OFFSET;
    commands[0] = (uint8_t)(0xB0U | page);
    commands[1] = (uint8_t)(0x10U | ((column >> 4U) & 0x0FU));
    commands[2] = (uint8_t)(column & 0x0FU);
    oled_write_stream(commands, 3U, 0U);
}

