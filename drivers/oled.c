static void oled_delay_ms(uint32_t milliseconds)
{
    while (milliseconds > 0U)
    {
        delay_cycles((uint32_t)(OLED_CPU_CLOCK_HZ / 1000U));
        milliseconds--;
    }
}

static void oled_spi_delay(void)
{
#if OLED_SPI_DELAY_CYCLES > 0
    delay_cycles((uint32_t)OLED_SPI_DELAY_CYCLES);
#endif
}

static void oled_spi_write_raw(uint8_t value)
{
    uint8_t bit;

    for (bit = 0U; bit < 8U; bit++)
    {
        OLED_SCL_LOW();
        if ((value & 0x80U) != 0U)
        {
            OLED_SDA_HIGH();
        }
        else
        {
            OLED_SDA_LOW();
        }
        oled_spi_delay();
        OLED_SCL_HIGH();
        oled_spi_delay();
        value <<= 1U;
    }
}

static void oled_write_stream(const uint8_t *data, uint16_t length, uint8_t is_data)
{
    uint16_t index;

    if ((data == NULL) || (length == 0U))
    {
        return;
    }

    if (is_data != 0U)
    {
        OLED_DC_HIGH();
    }
    else
    {
        OLED_DC_LOW();
    }

    OLED_CS_LOW();
    for (index = 0U; index < length; index++)
    {
        oled_spi_write_raw(data[index]);
    }
    OLED_CS_HIGH();
}

static uint8_t oled_font_index(char character)
{
    uint8_t value = (uint8_t)character;

    if ((value < 32U) || (value > 126U))
    {
        value = (uint8_t)'?';
    }
    return (uint8_t)(value - 32U);
}

static uint8_t oled_u64_to_ascii(uint64_t value, char *output)
{
    char reverse[21];
    uint8_t count = 0U;
    uint8_t index;

    do
    {
        reverse[count] = (char)('0' + (char)(value % 10U));
        value /= 10U;
        count++;
    } while ((value != 0U) && (count < (uint8_t)sizeof(reverse)));

    for (index = 0U; index < count; index++)
    {
        output[index] = reverse[(uint8_t)(count - index - 1U)];
    }
    return count;
}

static void oled_format_float(char *output, float value, uint8_t decimals, uint8_t trim_zeros)
{
    static const uint32_t powers_of_ten[] = {
        1U, 10U, 100U, 1000U, 10000U, 100000U, 1000000U};
    uint8_t position = 0U;
    uint8_t index;
    uint32_t scale;
    uint32_t divisor;
    uint64_t scaled;
    uint64_t whole;
    uint32_t fraction;
    float magnitude;

    if (value != value)
    {
        output[0] = 'n';
        output[1] = 'a';
        output[2] = 'n';
        output[3] = 0;
        return;
    }

    if ((value > 999999999.0f) || (value < -999999999.0f))
    {
        output[0] = 'o';
        output[1] = 'v';
        output[2] = 'f';
        output[3] = 0;
        return;
    }

    if (decimals > 6U)
    {
        decimals = 6U;
    }

    if (value < 0.0f)
    {
        output[position] = '-';
        position++;
        magnitude = -value;
    }
    else
    {
        magnitude = value;
    }

    scale = powers_of_ten[decimals];
    scaled = (uint64_t)((magnitude * (float)scale) + 0.5f);
    whole = scaled / scale;
    fraction = (uint32_t)(scaled % scale);

    position = (uint8_t)(position + oled_u64_to_ascii(whole, &output[position]));

    if (decimals > 0U)
    {
        output[position] = '.';
        position++;
        divisor = scale / 10U;
        for (index = 0U; index < decimals; index++)
        {
            output[position] = (char)('0' + (char)(fraction / divisor));
            position++;
            fraction %= divisor;
            if (divisor > 1U)
            {
                divisor /= 10U;
            }
        }

        if (trim_zeros != 0U)
        {
            while ((position > 0U) && (output[position - 1U] == '0'))
            {
                position--;
            }
            if ((position > 0U) && (output[position - 1U] == '.'))
            {
                position--;
            }
        }
    }

    output[position] = 0;
}

static int16_t oled_abs_i16(int16_t value)
{
    return (value < 0) ? (int16_t)-value : value;
}

void OLED_GPIO_Init(void)
{
    DL_GPIO_initDigitalOutput(OLED_SCL_IOMUX);
    DL_GPIO_initDigitalOutput(OLED_SDA_IOMUX);
    DL_GPIO_initDigitalOutput(OLED_RST_IOMUX);
    DL_GPIO_initDigitalOutput(OLED_DC_IOMUX);
    DL_GPIO_initDigitalOutput(OLED_CS_IOMUX);

    OLED_SCL_HIGH();
    OLED_SDA_HIGH();
    OLED_RST_HIGH();
    OLED_DC_LOW();
    OLED_CS_HIGH();

    DL_GPIO_enableOutput(OLED_SCL_PORT, OLED_SCL_PIN);
    DL_GPIO_enableOutput(OLED_SDA_PORT, OLED_SDA_PIN);
    DL_GPIO_enableOutput(OLED_RST_PORT, OLED_RST_PIN);
    DL_GPIO_enableOutput(OLED_DC_PORT, OLED_DC_PIN);
    DL_GPIO_enableOutput(OLED_CS_PORT, OLED_CS_PIN);
}

