void OLED_DrawCircle(int16_t x0, int16_t y0, int16_t radius, uint8_t color)
{
    int16_t x;
    int16_t y;
    int16_t decision;

    if (radius < 0)
    {
        return;
    }

    x = radius;
    y = 0;
    decision = (int16_t)(1 - radius);

    while (x >= y)
    {
        OLED_DrawPixel((int16_t)(x0 + x), (int16_t)(y0 + y), color);
        OLED_DrawPixel((int16_t)(x0 + y), (int16_t)(y0 + x), color);
        OLED_DrawPixel((int16_t)(x0 - y), (int16_t)(y0 + x), color);
        OLED_DrawPixel((int16_t)(x0 - x), (int16_t)(y0 + y), color);
        OLED_DrawPixel((int16_t)(x0 - x), (int16_t)(y0 - y), color);
        OLED_DrawPixel((int16_t)(x0 - y), (int16_t)(y0 - x), color);
        OLED_DrawPixel((int16_t)(x0 + y), (int16_t)(y0 - x), color);
        OLED_DrawPixel((int16_t)(x0 + x), (int16_t)(y0 - y), color);

        y++;
        if (decision <= 0)
        {
            decision = (int16_t)(decision + (2 * y) + 1);
        }
        else
        {
            x--;
            decision = (int16_t)(decision + (2 * (y - x)) + 1);
        }
    }
}

void OLED_FillCircle(int16_t x0, int16_t y0, int16_t radius, uint8_t color)
{
    int16_t x;
    int16_t y;
    int32_t limit;

    if (radius < 0)
    {
        return;
    }

    limit = (int32_t)radius * radius;
    for (y = (int16_t)-radius; y <= radius; y++)
    {
        for (x = (int16_t)-radius; x <= radius; x++)
        {
            if ((((int32_t)x * x) + ((int32_t)y * y)) <= limit)
            {
                OLED_DrawPixel((int16_t)(x0 + x), (int16_t)(y0 + y), color);
            }
        }
    }
}

